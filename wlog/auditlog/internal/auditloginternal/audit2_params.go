package auditloginternal

import (
	"maps"

	"github.com/palantir/pkg/datetime"
	"github.com/palantir/witchcraft-go-logging/conjure/witchcraft-logging-api/witchcraft/api/logging"
	"github.com/palantir/witchcraft-go-logging/wlog"
	wloginternal "github.com/palantir/witchcraft-go-logging/wlog/internal"
)

const (
	Audit2TypeValue = "audit.2"

	Audit2OtherUIDsKey     = "otherUids"
	Audit2OriginKey        = "origin"
	Audit2NameKey          = "name"
	Audit2ResultKey        = "result"
	Audit2RequestParamsKey = "requestParams"
	Audit2ResultParamsKey  = "resultParams"
)

// Audit2Param marks an AuditParam as native to audit.2.
type Audit2Param struct {
	Param AuditParam
}

func Audit2ToParams(atLogTimeValuesProvider *atLogTimeValues, name string, result AuditResultType, inParams []Audit2Param) []wlog.Param {
	return []wlog.Param{audit2ObjectToParam(BuildAuditLogV2(atLogTimeValuesProvider, name, result, inParams))}
}

// BuildAuditLogV2 allocates a fresh logging.AuditLogV2, populates required fields, applies the provided params, and
// returns the populated struct, suitable for direct emission through LogAuditLogV2.
//
// Hot-path callers may use populateAuditLogV2 with a pre-allocated (e.g., pooled) struct instead.
func BuildAuditLogV2(atLogTimeValuesProvider *atLogTimeValues, name string, result AuditResultType, inParams []Audit2Param) *logging.AuditLogV2 {
	log := new(logging.AuditLogV2)
	populateAuditLogV2(log, atLogTimeValuesProvider, name, result, inParams)
	return log
}

// populateAuditLogV2 populates a caller-provided logging.AuditLogV2 with the required fields, applies the provided
// params, and propagates a sibling v3 emission's logEntryId if one was set on atLogTimeValuesProvider.
func populateAuditLogV2(log *logging.AuditLogV2, atLogTimeValuesProvider *atLogTimeValues, name string, result AuditResultType, inParams []Audit2Param) {
	if atLogTimeValuesProvider == nil {
		atLogTimeValuesProvider = &atLogTimeValues{}
	}
	log.Type = Audit2TypeValue
	log.Time = datetime.DateTime(atLogTimeValuesProvider.getOrComputeTimeValue())
	log.Name = name
	log.Result = logging.New_AuditResult(logging.AuditResult_Value(result))
	for _, p := range inParams {
		if p.Param.Audit2ParamFn != nil {
			p.Param.Audit2ParamFn(log)
		}
	}
	wloginternal.OmitEmpty(&log.Uid)
	wloginternal.OmitEmpty(&log.Sid)
	wloginternal.OmitEmpty(&log.TokenId)
	wloginternal.OmitEmpty(&log.OrgId)
	wloginternal.OmitEmpty(&log.TraceId)
	wloginternal.OmitEmpty(&log.Origin)
	// if LogEntryID was generated by a sibling v3 emission, propagate it as a request param
	if logEntryIDValue := atLogTimeValuesProvider.getLogEntryIDValue(); logEntryIDValue != nil {
		wloginternal.SetMapParam(&log.RequestParams, "_auditLogEntryId", any(*logEntryIDValue))
	}
}

// audit2ObjectToParam emits all set fields of an AuditLogV2 to a wlog.LogEntry.
func audit2ObjectToParam(log *logging.AuditLogV2) wlog.Param {
	return wlog.NewParam(func(entry wlog.LogEntry) {
		entry.StringValue(wlog.TypeKey, log.Type)
		entry.StringValue(wlog.TimeKey, log.Time.String())
		entry.StringValue(Audit2NameKey, log.Name)
		entry.StringValue(Audit2ResultKey, string(log.Result.Value()))
		ApplyAudit2ObjectParams(log, entry)
	})
}

func ApplyAudit2ObjectParams(log *logging.AuditLogV2, entry wlog.LogEntry) {
	if log.Uid != nil {
		entry.OptionalStringValue(wlog.UIDKey, string(*log.Uid))
	}
	if log.Sid != nil {
		entry.OptionalStringValue(wlog.SIDKey, string(*log.Sid))
	}
	if log.TokenId != nil {
		entry.OptionalStringValue(wlog.TokenIDKey, string(*log.TokenId))
	}
	if log.OrgId != nil {
		entry.OptionalStringValue(wlog.OrgIDKey, string(*log.OrgId))
	}
	if log.TraceId != nil {
		entry.OptionalStringValue(wlog.TraceIDKey, string(*log.TraceId))
	}
	if log.OtherUids != nil {
		uids := make([]string, len(log.OtherUids))
		for i, u := range log.OtherUids {
			uids[i] = string(u)
		}
		entry.StringListValue(Audit2OtherUIDsKey, uids)
	}
	if log.Origin != nil {
		entry.OptionalStringValue(Audit2OriginKey, *log.Origin)
	}
	if len(log.RequestParams) > 0 {
		entry.AnyMapValue(Audit2RequestParamsKey, log.RequestParams)
	}
	if len(log.ResultParams) > 0 {
		entry.AnyMapValue(Audit2ResultParamsKey, log.ResultParams)
	}
}
func Audit2UID(uid string) Audit2Param {
	return Audit2Param{Param: uidParam(uid)}
}

func Audit2SID(sid string) Audit2Param {
	return Audit2Param{Param: sidParam(sid)}
}

func Audit2TokenID(tokenID string) Audit2Param {
	return Audit2Param{Param: tokenIDParam(tokenID)}
}

func Audit2OrgID(orgID string) Audit2Param {
	return Audit2Param{Param: orgIDParam(orgID)}
}

func Audit2TraceID(traceID string) Audit2Param {
	return Audit2Param{Param: traceIDParam(traceID)}
}

func Audit2OtherUIDs(otherUIDs ...string) Audit2Param {
	return Audit2Param{
		Param: AuditParam{
			Audit2ParamFn: func(log *logging.AuditLogV2) {
				uids := make([]logging.UserId, len(otherUIDs))
				for i, u := range otherUIDs {
					uids[i] = logging.UserId(u)
				}
				log.OtherUids = uids
			},
		},
	}
}

func Audit2Origin(origin string) Audit2Param {
	return Audit2Param{Param: originParam(origin)}
}

func Audit2RequestParam(key string, value any) Audit2Param {
	return Audit2Param{Param: AuditParam{
		Audit2ParamFn: func(log *logging.AuditLogV2) {
			wloginternal.SetMapParam(&log.RequestParams, key, value)
		},
		Audit3ParamFn: func(log *logging.AuditLogV3) {
			if category, ok := value.(string); key == "category" && ok {
				log.Categories = append(log.Categories, category)
				return
			}
			wloginternal.SetMapParam(&log.RequestFields, key, value)
		},
	}}
}

func Audit2RequestParams(requestParams map[string]any) Audit2Param {
	return Audit2Param{
		Param: AuditParam{
			Audit2ParamFn: func(log *logging.AuditLogV2) {
				wloginternal.SetMapParams(&log.RequestParams, requestParams)
			},
			Audit3ParamFn: func(log *logging.AuditLogV3) {
				// In v3, "category" gets pulled out into Categories; the rest goes to RequestFields.
				params := requestParams
				if categoryVal, ok := requestParams["category"]; ok {
					if categoryValString, ok := categoryVal.(string); ok {
						params = maps.Clone(requestParams)
						delete(params, "category")
						log.Categories = append(log.Categories, categoryValString)
					}
				}
				wloginternal.SetMapParams(&log.RequestFields, params)
			},
		},
	}
}

func Audit2ResultParam(key string, value any) Audit2Param {
	return Audit2Param{Param: AuditParam{
		Audit2ParamFn: func(log *logging.AuditLogV2) {
			wloginternal.SetMapParam(&log.ResultParams, key, value)
		},
		Audit3ParamFn: func(log *logging.AuditLogV3) {
			wloginternal.SetMapParam(&log.ResultFields, key, value)
		},
	}}
}

func Audit2ResultParams(resultParams map[string]any) Audit2Param {
	return Audit2Param{
		Param: AuditParam{
			Audit2ParamFn: func(log *logging.AuditLogV2) {
				wloginternal.SetMapParams(&log.ResultParams, resultParams)
			},
			Audit3ParamFn: func(log *logging.AuditLogV3) {
				wloginternal.SetMapParams(&log.ResultFields, resultParams)
			},
		},
	}
}
