// Run this generator to update the "categories.go" file with content that matches the Java declarations in an
// "AuditCategoryConfiguration.java" file.
func main() {
	if len(os.Args) < 2 {
		_, _ = fmt.Fprintf(os.Stderr, "Usage: %s <path to input Java file>\n", os.Args[0])
		os.Exit(1)
	}

	if err := runLogic(os.Args[1]); err != nil {
		_, _ = fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
}

